    def get_user(self, user_id):
        """Получение данных пользователя по ID"""
        self.cursor.execute(
            'SELECT name, zodiac_sign FROM users WHERE user_id = ?',
            (user_id,)
        )
        return self.cursor.fetchone()

    def save_user_name(self, user_id, name):
        """Сохранение имени пользователя"""
        # INSERT OR REPLACE позволяет создать новую запись или обновить существующую
        self.cursor.execute('''
            INSERT INTO users (user_id, name, zodiac_sign)
            VALUES (?, ?, NULL)
            ON CONFLICT(user_id) DO UPDATE SET name=excluded.name
        ''', (user_id, name))
        self.conn.commit()

    def save_user_zodiac(self, user_id, zodiac_sign):
        """Сохранение знака зодиака пользователя"""
        self.cursor.execute('''
            UPDATE users SET zodiac_sign = ? WHERE user_id = ?
        ''', (zodiac_sign, user_id))
        self.conn.commit()

    def get_predictions_by_category(self, category):
        """Получение всех предсказаний для определенной категории"""
        self.cursor.execute(
            'SELECT text FROM predictions WHERE category = ?',
            (category,)
        )
        return [row[0] for row in self.cursor.fetchall()]

    def close(self):
        """Закрытие соединения с базой данных"""
        self.conn.close()